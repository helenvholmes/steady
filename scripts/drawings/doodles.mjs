// Builds the goal icons in public/doodles/ from Doodle Icons by Khushmeen Sidhu (https://khushmeen.com/icons),
// released under CC0. The icons come from the doodle-icons npm package (MIT), rendered here with React 18:
//
//   cd scripts/drawings && npm install && npm run generate
//
// Each icon becomes a static SVG with navy ink (dark mode inverts it in CSS). Brand logos and interface arrows
// are left out: logos are trademarks, and arrows don't make sense as a goal's picture.
// Outputs: public/doodles/<id>.svg, src/lib/doodles/catalog.ts, and a LICENSE.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as Doodles from "doodle-icons";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const outDir = path.join(root, "public/doodles");
const libDir = path.join(root, "src/lib/doodles");

const INK = "#1d2433";
const CATEGORIES = [
  ["Interfaces", "Everyday"],
  ["Objects", "Objects"],
  ["Misc", "Misc"],
  ["Food", "Food"],
  ["Health", "Health"],
  ["Weather", "Weather"],
  ["Finance", "Finance"],
  ["Currency", "Currency"],
  ["ECommerce", "Shopping"],
  ["Files", "Files"],
  ["Emojis", "Faces"],
  ["HandGestures", "Hands"],
  ["GenderSymbols", "Symbols"],
];

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])(\d)/g, "$1-$2").toLowerCase();
const label = (s) => {
  const words = s.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/([A-Za-z])(\d)/g, "$1 $2").toLowerCase();
  return words[0].toUpperCase() + words.slice(1);
};

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
mkdirSync(libDir, { recursive: true });

const icons = [];
for (const [key, category] of CATEGORIES) {
  for (const [name, Component] of Object.entries(Doodles[key] ?? {})) {
    const id = `${kebab(key === "Interfaces" ? "" : key)}${key === "Interfaces" ? "" : "-"}${kebab(name)}`;
    // Paths carry no fill of their own (they default to black); the root sets navy ink for all of them.
    const svg = renderToStaticMarkup(React.createElement(Component))
      .replace(/^<svg /, `<svg fill="${INK}" `)
      .replace(/(\d+\.\d{2})\d+/g, "$1");
    writeFileSync(path.join(outDir, `${id}.svg`), svg);
    icons.push({ id, label: label(name), category });
  }
}

writeFileSync(
  path.join(libDir, "catalog.ts"),
  `// Generated by scripts/drawings/doodles.mjs. Do not edit by hand.
// Icons: Doodle Icons by Khushmeen Sidhu (https://khushmeen.com/icons), CC0.

export const DOODLE_CATEGORIES = ${JSON.stringify(CATEGORIES.map((c) => c[1]))} as const;

export const DOODLES = ${JSON.stringify(icons)} as const;
`,
);
writeFileSync(
  path.join(outDir, "LICENSE.md"),
  `These icons are Doodle Icons by Khushmeen Sidhu (https://khushmeen.com/icons), released under CC0 1.0
(public domain). They were recolored by scripts/drawings/doodles.mjs using the doodle-icons npm package (MIT).
`,
);
console.log(`Wrote ${icons.length} icons in ${CATEGORIES.length} categories to public/doodles/`);
